def build_journal(path: Path, seed: int = 0) -> None:
    rng = random.Random(seed)
    lines = ["ЖУРНАЛ ЭКСПЕРИМЕНТОВ ЛАБОРАТОРИИ, 2025 г.",
             "Записи ведут дежурные исследователи; каждый запуск получает номер run-N.", ""]
    run, day = 100, date(2025, 1, 9)
    while day <= date(2025, 12, 26):
        if day.weekday() < 5:
            for _ in range(rng.choice([2, 3, 3, 4])):
                run += 1
                model, lr_name = rng.choice(MODELS)
                dataset = "cifar10-subset-v2" if day >= date(2025, 6, 2) and rng.random() < 0.5 else rng.choice(DATASETS)
                opt = "Lion" if model == "ViT-S/16" and day >= date(2025, 11, 5) else rng.choice(OPTIMIZERS)
                lr = rng.choice(["1e-3", "3e-4", "5e-4", "0.05", "0.1"])
                acc = 0.9731 if run == BEST_RUN else round(rng.uniform(0.80, 0.965), 4)
                lines.append(f"{day.isoformat()} | run-{run} | {model} | {dataset} | {opt}, {lr_name}={lr}, "
                             f"batch={rng.choice([64, 128, 256])}, epochs={rng.choice([20, 30, 50])} | "
                             f"val accuracy {acc} | {rng.choice(ROUTINE)}.")
        if day in NEEDLES:
            lines.append(f"{day.isoformat()} | СОБЫТИЕ | {NEEDLES[day].format(run=f'run-{run}')}")
        day += timedelta(days=1)
    path.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))


