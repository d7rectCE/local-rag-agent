def build_contract(path: Path) -> None:
    from datetime import datetime, timezone

    from demo_documents import normalize_zip
    from docx import Document

    doc = Document()
    doc.core_properties.author = "Заказчик"
    doc.core_properties.title = "Договор № 17/НИР-2026"
    doc.core_properties.created = doc.core_properties.modified = datetime(2026, 1, 12, 9, 0, tzinfo=timezone.utc)
    doc.core_properties.last_modified_by = "Заказчик"
    doc.core_properties.revision = 1
    for kind, content in CONTRACT:
        if kind == "title":
            doc.add_heading(content, level=0)
        elif kind == "h":
            doc.add_heading(content, level=1)
        elif kind == "p":
            doc.add_paragraph(content)
        else:
            table = doc.add_table(rows=len(content), cols=len(content[0]))
            for r, row in enumerate(content):
                for c, cell in enumerate(row):
                    table.cell(r, c).text = cell
    doc.save(path)
    normalize_zip(path, stamp=(2026, 1, 12, 0, 0, 0))  # reproducible archive timestamps


